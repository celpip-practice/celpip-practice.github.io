export const DICT: Record<Lang, Record<Key, string>> = { zh, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICT[lang][key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

export function skillName(t: T, s: Skill) {
  return t(`skill.${s}` as Key);
}

export function partName(t: T, s: Skill, n: number) {
  return t(`part.${s}.${n}` as Key);
}

export function testTitle(t: T, x: { set: number; test: number; label?: string }) {
  return x.label ? t("title.extra", { test: x.test }) : t("title.set", { set: x.set, test: x.test });
}
